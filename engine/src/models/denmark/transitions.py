class Transition(Enum):
    LEACHING = leaching
    ECONOMY = economy
    YIELD = crop_yield
    SIMILARITY = similarity


def get_index(crop: Crop, soil: Soil) -> int:
    # We subtract 1 since the names are indexed by 1 and not 0
    # We also subtract 1 from the crop length, since we also have the Other crop class
    return ((soil.value - 1) * (len(Crop) - 1)) + (crop.value - 1)


def get_transition(
    from_crop: Crop,
    to_crop: Crop,
    soil: Soil,
    retention: float,
    area: float,
    transition: Transition,
) -> float | None:
    try:
        value_per_ha = transition.value[get_index(from_crop, soil)][
            get_index(to_crop, soil)
        ]

        if value_per_ha == "" or value_per_ha == "-":
            return None

        value = int(value_per_ha) * area

        if transition == Transition.LEACHING:
            value = value * ((100 - retention) / 100)

        return value
    except IndexError:
        raise Exception(
            f"Transition is not legal. \n {from_crop} -> {to_crop} {soil} {retention} {area}, {get_index(from_crop, soil)}, {get_index(to_crop, soil)}"
        )


# This is the function calculating the values from our crop rotation
# In general the entire framework is based on the idea that we have a crop rotation, transition and spatial indicators.
def f(
    crop_rotation: CropRotation,
    transition: Transition,
    spatial_indicator: SpatialIndicator,
) -> float:
    values = []
    for idx, crop in enumerate(crop_rotation.indices):
        # We specifically want -1 if it is the first crop, since it is a rotation.
        previous_crop = crop_rotation.indices[idx - 1]
        value = get_transition(
            from_crop=previous_crop,
            to_crop=crop,
            soil=spatial_indicator.soil,
            retention=spatial_indicator.retention,
            area=spatial_indicator.area,
            transition=transition,
        )

        if value is None:
            raise Exception(
                f"The existing data should not contain invalid transitions \n {crop_rotation} {spatial_indicator} {transition}, {previous_crop} -> {crop} = {value}"
            )

        values.append(value)

    # We return the average of the values, so we can have different lengths of crop rotations
    return sum(values) / len(values)
